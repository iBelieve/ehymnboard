"""Turns PEM root CA files into a C++ header of DER arrays for tls.cpp.

Usage: embed_roots.py OUTPUT_HEADER PEM_FILE...

Each certificate in a PEM file needs a "# Name: ..." comment line somewhere
above it (and below the previous certificate); the firmware logs that name.
"""

import base64
import re
import sys
from pathlib import Path

# The name is the rest of its own line (DOTALL would let `.` run on into the
# next), and not blank
CERT = re.compile(
    r"^# Name: (?P<name>[^\n]*?\S)[^\S\n]*$(?P<between>.*?)"
    r"^-----BEGIN CERTIFICATE-----$(?P<body>.*?)^-----END CERTIFICATE-----$",
    re.MULTILINE | re.DOTALL,
)


def read_roots(path: Path) -> list[tuple[str, bytes]]:
    text = path.read_text()
    roots = []
    for match in CERT.finditer(text):
        between = match.group("between")
        if "-----BEGIN CERTIFICATE-----" in between:
            sys.exit(f"{path}: a certificate has no '# Name:' line above it")
        if re.search(r"^# Name: ", between, re.MULTILINE):
            sys.exit(f"{path}: a certificate has two '# Name:' lines above it")
        roots.append((match.group("name"), base64.b64decode(match.group("body"))))
    if len(roots) != text.count("-----BEGIN CERTIFICATE-----"):
        sys.exit(f"{path}: every certificate needs a '# Name:' line above it")
    return roots


def header(roots: list[tuple[str, bytes]]) -> str:
    lines = [
        "// Generated by cmake/embed_roots.py from the certs/ PEM files: don't edit",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "struct TlsRoot",
        "{",
        "    const char *name;",
        "    const uint8_t *der;",
        "    std::size_t length;",
        "};",
        "",
    ]
    for i, (_, der) in enumerate(roots):
        body = ",".join(str(b) for b in der)
        lines.append(f"inline constexpr uint8_t TLS_ROOT_{i}[] = {{{body}}};")
    lines += ["", "inline constexpr TlsRoot TLS_ROOTS[] = {"]
    for i, (name, _) in enumerate(roots):
        escaped = name.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'    {{"{escaped}", TLS_ROOT_{i}, sizeof(TLS_ROOT_{i})}},')
    lines += ["};", ""]
    return "\n".join(lines)


def main() -> None:
    # An output and at least one PEM file
    if not sys.argv[2:]:
        sys.exit(__doc__)
    roots = [root for path in sys.argv[2:] for root in read_roots(Path(path))]
    output = Path(sys.argv[1])
    text = header(roots)
    # Only touch the header when it changes, so nothing rebuilds needlessly
    if not output.exists() or output.read_text() != text:
        output.write_text(text)


if __name__ == "__main__":
    main()
