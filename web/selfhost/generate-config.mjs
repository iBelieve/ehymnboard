// Writes dist/workerd.capnp (plus the assets Worker it embeds), the workerd config for self-hosting the built
// Worker (see Dockerfile). Compatibility settings come from the build's
// wrangler.json, so they can't drift from what Cloudflare would run.

import { copyFileSync, readFileSync, writeFileSync } from "node:fs";

const dist = new URL("../dist/", import.meta.url);
const wrangler = JSON.parse(readFileSync(new URL("ehymnboard/wrangler.json", dist), "utf8"));

const flags = wrangler.compatibility_flags.map((flag) => JSON.stringify(flag)).join(", ");
const classes = wrangler.durable_objects.bindings.map((binding) => binding.class_name);

const config = `# Generated by selfhost/generate-config.mjs. Do not edit.
using Workerd = import "/workerd/workerd.capnp";

const config :Workerd.Config = (
  services = [
    (name = "main", worker = .main),
    (name = "assets", worker = .assets),
    # Overridden at runtime with --directory-path.
    (name = "client-files", disk = (path = "client")),
    (name = "do-storage", disk = (path = "data", writable = true)),
    (name = "internet", network = (allow = ["public"], tlsOptions = (trustBrowserCas = true))),
  ],
  # Overridden at runtime with --socket-addr.
  sockets = [(name = "http", address = "0.0.0.0:5000", http = (), service = "main")],
);

const main :Workerd.Worker = (
  modules = [(name = "index.js", esModule = embed "ehymnboard/index.js")],
  compatibilityDate = ${JSON.stringify(wrangler.compatibility_date)},
  compatibilityFlags = [${flags}],
  bindings = [
    (name = "ASSETS", service = "assets"),
${wrangler.durable_objects.bindings
  .map(
    (b) =>
      `    (name = ${JSON.stringify(b.name)}, durableObjectNamespace = ${JSON.stringify(b.class_name)}),`,
  )
  .join("\n")}
    (name = "BASIC_AUTH_USERNAME", fromEnvironment = "BASIC_AUTH_USERNAME"),
    (name = "BASIC_AUTH_PASSWORD", fromEnvironment = "BASIC_AUTH_PASSWORD"),
  ],
  durableObjectNamespaces = [
${classes.map((name) => `    (className = ${JSON.stringify(name)}, uniqueKey = "ehymnboard-${name}", enableSql = true),`).join("\n")}
  ],
  durableObjectStorage = (localDisk = "do-storage"),
  globalOutbound = "internet",
);

const assets :Workerd.Worker = (
  modules = [(name = "assets.js", esModule = embed "selfhost-assets.js")],
  compatibilityDate = ${JSON.stringify(wrangler.compatibility_date)},
  bindings = [(name = "FILES", service = "client-files")],
);
`;

// Embedded files are read when workerd starts, so everything lives in dist/.
copyFileSync(new URL("assets.js", import.meta.url), new URL("selfhost-assets.js", dist));
writeFileSync(new URL("workerd.capnp", dist), config);
console.log("Wrote dist/workerd.capnp");
