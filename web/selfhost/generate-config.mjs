// Writes dist/workerd.capnp (plus the assets Worker it embeds), the workerd config for self-hosting the built
// Worker (see Dockerfile). Compatibility settings come from the build's
// wrangler.json, so they can't drift from what Cloudflare would run.

import { randomUUID } from "node:crypto";
import { copyFileSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dist = new URL("../dist/", import.meta.url);
// The Vite plugin writes the Worker to dist/<name from wrangler.jsonc>/ and
// points .wrangler/deploy/config.json at its wrangler.json; follow that rather
// than hard-coding the name.
const deployConfig = new URL("../.wrangler/deploy/config.json", import.meta.url);
const wranglerJson = new URL(
  JSON.parse(readFileSync(deployConfig, "utf8")).configPath,
  deployConfig,
);
const worker = path.basename(path.dirname(fileURLToPath(wranglerJson)));
const wrangler = JSON.parse(readFileSync(wranglerJson, "utf8"));

const flags = wrangler.compatibility_flags.map((flag) => JSON.stringify(flag)).join(", ");
const classes = wrangler.durable_objects.bindings.map((binding) => binding.class_name);
// The Worker's chunks besides index.js (Better Auth, loaded when first used),
// named as index.js imports them.
const chunks = readdirSync(new URL(`${worker}/assets/`, dist))
  .filter((file) => file.endsWith(".js"))
  .map((file) => `(name = "assets/${file}", esModule = embed "${worker}/assets/${file}")`);
const modules = [`(name = "index.js", esModule = embed "${worker}/index.js")`, ...chunks];

const config = `# Generated by selfhost/generate-config.mjs. Do not edit.
using Workerd = import "/workerd/workerd.capnp";

const config :Workerd.Config = (
  services = [
    (name = "main", worker = .main),
    (name = "assets", worker = .assets),
    # Overridden at runtime with --directory-path.
    (name = "client-files", disk = (path = "client")),
    (name = "do-storage", disk = (path = "data", writable = true)),
    (name = "internet", network = (allow = ["public"], tlsOptions = (trustBrowserCas = true))),
  ],
  # Overridden at runtime with --socket-addr.
  sockets = [(name = "http", address = "0.0.0.0:8000", http = (), service = "main")],
);

const main :Workerd.Worker = (
  modules = [
${modules.map((module) => `    ${module},`).join("\n")}
  ],
  compatibilityDate = ${JSON.stringify(wrangler.compatibility_date)},
  compatibilityFlags = [${flags}],
  bindings = [
    (name = "ASSETS", service = "assets"),
${wrangler.durable_objects.bindings
  .map(
    (b) =>
      `    (name = ${JSON.stringify(b.name)}, durableObjectNamespace = ${JSON.stringify(b.class_name)}),`,
  )
  .join("\n")}
    (name = "BETTER_AUTH_SECRET", fromEnvironment = "BETTER_AUTH_SECRET"),
    (name = "SETUP_PASSWORD", fromEnvironment = "SETUP_PASSWORD"),
    (name = "EXTRA_DEVICE_IDS", fromEnvironment = "EXTRA_DEVICE_IDS"),
    # The self-hosted image is production's fallback, so it pings
    # healthchecks.io, as the production Worker does (wrangler.jsonc).
    (name = "HEALTHCHECKS", text = "on"),
    # workerd has no version metadata binding, so each run of this script
    # makes an ID (a cached Docker layer keeps the last one, which is fine: a
    # restart closes every socket anyway).
    (name = "CF_VERSION_METADATA", json = ${JSON.stringify(JSON.stringify({ id: randomUUID(), tag: "", timestamp: new Date().toISOString() }))}),
  ],
  durableObjectNamespaces = [
${classes.map((name) => `    (className = ${JSON.stringify(name)}, uniqueKey = "ehymnboard-${name}", enableSql = true),`).join("\n")}
  ],
  durableObjectStorage = (localDisk = "do-storage"),
  globalOutbound = "internet",
);

const assets :Workerd.Worker = (
  modules = [(name = "assets.js", esModule = embed "selfhost-assets.js")],
  compatibilityDate = ${JSON.stringify(wrangler.compatibility_date)},
  bindings = [(name = "FILES", service = "client-files")],
);
`;

// Embedded files are read when workerd starts, so everything lives in dist/.
copyFileSync(new URL("assets.js", import.meta.url), new URL("selfhost-assets.js", dist));
writeFileSync(new URL("workerd.capnp", dist), config);
console.log("Wrote dist/workerd.capnp");
